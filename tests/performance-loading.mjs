import fs from 'node:fs';
import assert from 'node:assert/strict';
const html=fs.readFileSync('public/workspace/index.html','utf8');
const app=fs.readFileSync('public/assets/js/app.js','utf8');
const sw=fs.readFileSync('public/sw.js','utf8');
for(const library of ['pdf-lib','pdf.min.js','xlsx.full.min.js','jspdf.umd.min.js','docx','pptxgen.min.js','jszip']) assert.ok(!html.split('<script src=').some(tag=>tag.includes(library)),`${library} must not load initially`);
assert.ok(html.includes('<script src="/assets/js/app.js" defer>'),'Workspace script must resolve from /workspace/');
assert.ok(html.includes('cdn.tailwindcss.com')&&html.includes('defer'),'Tailwind runtime must be deferred');
assert.ok(html.includes('fonts.googleapis.com')&&html.includes('media="print"'),'Google Fonts must load asynchronously');
assert.ok(html.includes('font-awesome')&&html.includes('media="print"'),'Icon stylesheet must load asynchronously');
for(const loader of ['ensurePdfLib','ensurePdfJs','processWord','processExcel','processPPT']) assert.ok(app.includes(loader),`${loader} lazy loader must exist`);
assert.ok(app.includes('SCRIPT_LOADS = new Map()'),'Concurrent library requests must be deduplicated');
assert.ok(!sw.includes('/assets/js/pdf/'),'PDF modules must not be precached');
console.log('Performance loading checks passed.');
